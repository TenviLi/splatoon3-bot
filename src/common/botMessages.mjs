function defineBotMessages({
  rainmakerLong,
  rainmakerShort,
  scheduleHeader,
  salmonRunHeader,
  dailyDropGearHeader,
  regularGearHeader,
  scheduleSource,
  scheduleTitle,
  scheduleAction,
  salmonRunSource,
  randomWeapons,
  salmonRunAction,
  dailyDropGearAction,
  regularGearTitle,
  regularGearAction,
}) {
  return Object.freeze({
    screenshot: Object.freeze({
      rainmakerLong,
      rainmakerShort,
      headers: Object.freeze({
        schedules: scheduleHeader,
        salmonRun: salmonRunHeader,
        dailyDropGear: dailyDropGearHeader,
        regularGear: regularGearHeader,
      }),
    }),
    notification: Object.freeze({
      schedules: Object.freeze({ source: scheduleSource, title: scheduleTitle, action: scheduleAction }),
      salmonRun: Object.freeze({ source: salmonRunSource, randomWeapons, action: salmonRunAction }),
      dailyDropGear: Object.freeze({ action: dailyDropGearAction }),
      regularGear: Object.freeze({ title: regularGearTitle, action: regularGearAction }),
    }),
  })
}

