import { defineBotLocaleMap } from './botLocale.mjs'

function defineBotMessages({
  rainmakerLong,
  rainmakerShort,
  scheduleHeader,
  salmonRunHeader,
  dailyDropGearHeader,
  regularGearHeader,
  scheduleSource,
  scheduleTitle,
  scheduleAction,
  focusedScheduleAction,
  challengeAction,
  challengeDetails,
  salmonRunSource,
  randomWeapons,
  salmonRunAction,
  dailyDropGearAction,
  dailyDropGearTitle,
  regularGearTitle,
  regularGearAction,
  salmonRunGearTitle,
  salmonRunGearHint,
  salmonRunGearAction,
  regionalSplatfestAction,
}) {
  return Object.freeze({
    screenshot: Object.freeze({
      rainmakerLong,
      rainmakerShort,
      headers: Object.freeze({
        schedules: scheduleHeader,
        salmonRun: salmonRunHeader,
        dailyDropGear: dailyDropGearHeader,
        regularGear: regularGearHeader,
      }),
    }),
    notification: Object.freeze({
      schedules: Object.freeze({
        source: scheduleSource,
        title: scheduleTitle,
        action: scheduleAction,
        focusedAction: focusedScheduleAction,
      }),
      challenges: Object.freeze({ action: challengeAction, details: challengeDetails }),
      salmonRun: Object.freeze({ source: salmonRunSource, randomWeapons, action: salmonRunAction }),
      dailyDropGear: Object.freeze({ action: dailyDropGearAction, title: dailyDropGearTitle }),
      regularGear: Object.freeze({ title: regularGearTitle, action: regularGearAction }),
      salmonRunGear: Object.freeze({
        title: salmonRunGearTitle,
        hint: salmonRunGearHint,
        action: salmonRunGearAction,
      }),
      splatfest: Object.freeze({ regionalAction: regionalSplatfestAction }),
    }),
  })
}

